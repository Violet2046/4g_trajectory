{
    if (!buf || ch < EPD_FONT_START || ch > EPD_FONT_END) return EPD_FONT_W;

    const uint8_t *glyph = epd_font_data +
                           (ch - EPD_FONT_START) * EPD_FONT_H;

    for (int col = 0; col < EPD_FONT_W; col++) {
        uint8_t bits = glyph[col];
        for (int row = 0; row < EPD_FONT_H; row++) {
            if (bits & (1 << row)) {
                int px = x + col;
                int py = y + row;
                if (px >= 0 && px < (int)EPD_WIDTH &&
                    py >= 0 && py < (int)EPD_HEIGHT) {
                    epd_set_pixel(buf, (uint16_t)px, (uint16_t)py,
                                  colour);
                }
            }
        }
    }
    return EPD_FONT_W;
}

int epd_draw_string(uint8_t *buf, int x, int y,
                    const char *str, uint8_t colour)
{
    if (!buf || !str) return 0;
    int cx = x;
    while (*str) {
        cx += epd_draw_char(buf, cx, y, *str++, colour);
    }
    return cx - x;
}

void epd_draw_string_wrap(uint8_t *buf, int x, int y,
                          const char *str, uint8_t colour, int margin_r)
{
    if (!buf || !str) return;
    int cx = x, cy = y;
    while (*str) {
        if (cy + EPD_FONT_H > (int)EPD_HEIGHT) break;  /* off bottom */
        if (*str == '\n') {
            cx = x;
            cy += EPD_FONT_H;
            str++;
            continue;
        }
        /* Wrap */
        if (cx + EPD_FONT_W > margin_r) {
            cx = x;
            cy += EPD_FONT_H;
            if (cy + EPD_FONT_H > (int)EPD_HEIGHT) break;
        }
        cx += epd_draw_char(buf, cx, cy, *str++, colour);
    }
}

int epd_text_width(const char *str)
{
    if (!str) return 0;
    int len = 0;
    while (*str++) len++;
    return len * EPD_FONT_W;
}
